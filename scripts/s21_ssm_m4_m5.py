# ========================== E1: readout machinery (s20 reuse) ==========================

def make_readout(F):
    W = torch.zeros(VOCAB, F, dtype=torch.float64)
    W[:, -1] = 1.0 / VOCAB
    P = torch.eye(F, dtype=torch.float64) / RLS_DELTA
    return W, P


def rls_update(W, P, phi, target, err_scale):
    e = err_scale * (target - (W @ phi))
    g = P @ phi
    k = g / (RLS_LAMBDA + float(phi @ g))
    W = W + torch.outer(e, k)
    P = (P - torch.outer(k, phi) @ P) / RLS_LAMBDA
    return W, P


def rls_refresh_P(P, phi):
    """Dormant-covariance refresh: advance the inverse covariance on the
    current feature stream with the weights frozen (zero error). Returns P
    only; the caller leaves W untouched."""
    g = P @ phi
    k = g / (RLS_LAMBDA + float(phi @ g))
    return (P - torch.outer(k, phi) @ P) / RLS_LAMBDA


# Guard for the frozen-weight arm: W must equal its initial value exactly.
# make_readout initialises W to a uniform prior (all columns zero except the
# bias 1/VOCAB), so the invariant is a direct comparison against a freshly
# initialised readout -- a magnitude test cannot distinguish "untouched" from
# "trained", because both states span 0..1/VOCAB.
FROZEN_W_TOL = 1e-12


def assert_W_still_frozen(W, W_init, arm, seed):
    if arm != 'A3-soft-frozenW':
        return
    drift = float((W - W_init).abs().max())
    if drift > FROZEN_W_TOL:
        raise AssertionError(
            f"{arm} seed {seed}: readout weights are not frozen "
            f"(max|W - W_init| = {drift:.3e}) -- the arm would silently "
            "reproduce A3-soft instead of testing dormancy")


def refs_fast(seed, A, B, scale):
    """Fast-channel metadata references (P2 host)."""
    fm = fast_mask_of(A)
    refs = []
    for d in range(2):
        rs = gen_stream(seed * 31 + d * 131 + 7, 1 if d == 0 else 7,
                        REF_LEN, BIAS_A if d == 0 else BIAS_B)
        h = torch.zeros(N_STATE, dtype=torch.float64)
        acc = torch.zeros(N_STATE, dtype=torch.float64)
        for t in range(REF_LEN):
            h = A * h + B[:, rs[t]]
            acc = acc + h * scale
        refs.append((acc / REF_LEN)[fm])
    return refs


def run_e1(args):
    """(arm, tau_m, seed) -> E1 metrics. Top-level; unbuffered."""
    if hasattr(sys.stdout, 'reconfigure'):
        sys.stdout.reconfigure(line_buffering=True)
        sys.stderr.reconfigure(line_buffering=True)
    arm, tau_m, seed = args
    t0 = time.time()

    torch.manual_seed(seed * SEED_SCALE + SEED_OFF)
    A, B = sample_substrate(seed, 'CV')
    scale = whiten_scale(A)
    fm = fast_mask_of(A)
    stream, domains = gen_drift_stream(seed)
    T = stream.shape[0]
    F = N_STATE + 1

    refs = refs_fast(seed, A, B, scale)
    sep = float(torch.norm(refs[0] - refs[1]))
    kappa = 0.5 * max(sep, 1e-6)      # softmax temperature (gentle scale)

    if arm == 'A1':
        W, P = make_readout(F)
        W0 = W1 = P0 = P1 = None
        W0_init = W1_init = None
    else:
        W0, P0 = make_readout(F)
        W1, P1 = make_readout(F)
        W = P = None
        W0_init = W0.clone()
        W1_init = W1.clone()

    slow = refs[0].clone()
    prev_est = 0
    last_switch_t = -10 ** 9

    ce = np.empty(T, dtype=np.float64)
    ce[:] = np.nan
    ce_unc = np.empty(T, dtype=np.float64)
    ce_unc[:] = np.nan
    nneg = 0
    nclip = 0
    n_unc_undef = 0
    h = torch.zeros(N_STATE, dtype=torch.float64)

    for t in range(1, T):
        h = A * h + B[:, stream[t - 1]]
        hw = h * scale

        if arm == 'A1':
            y_hat = (W @ torch.cat([B[:, stream[t - 1]],
                                    torch.ones(1, dtype=torch.float64)]))
            y_tok = y_hat[stream[t]]
            p_t = float(y_tok.clamp(min=1e-12, max=1.0))
            yt = float(y_tok)
            if yt <= 0.0:
                nneg += 1
            if yt <= 1e-12:
                nclip += 1
            if yt > 0.0:
                ce_unc[t] = -np.log(yt)
            else:
                n_unc_undef += 1
            ce[t] = -np.log(p_t)
            target = torch.zeros(VOCAB, dtype=torch.float64)
            target[stream[t]] = 1.0
            W, P = rls_update(W, P,
                              torch.cat([B[:, stream[t - 1]],
                                         torch.ones(1,
                                                    dtype=torch.float64)]),
                              target, 1.0)
        else:
            lam = 1.0 / tau_m
            slow = (1.0 - lam) * slow + lam * hw[fm]
            if arm == 'A3-abrupt':
                est = gate_estimate(slow, refs, prev_est, GATE_MARGIN)
                if est != prev_est:
                    last_switch_t = t
                    prev_est = est
                w0 = 1.0 if est == 0 else 0.0
                w1 = 1.0 - w0
            else:  # A3-soft: continuous softmax weights (no flip)
                d0 = float(torch.norm(slow - refs[0]))
                d1 = float(torch.norm(slow - refs[1]))
                w1 = 1.0 / (1.0 + np.exp((d1 - d0) / kappa))
                w0 = 1.0 - w1

            phi = torch.cat([B[:, stream[t - 1]],
                             torch.ones(1, dtype=torch.float64)])
            y_hat = w0 * (W0 @ phi) + w1 * (W1 @ phi)
            y_tok = y_hat[stream[t]]
            p_t = float(y_tok.clamp(min=1e-12, max=1.0))
            yt = float(y_tok)
            if yt <= 0.0:
                nneg += 1
            if yt <= 1e-12:
                nclip += 1
            if yt > 0.0:
                ce_unc[t] = -np.log(yt)
            else:
                n_unc_undef += 1
            ce[t] = -np.log(p_t)
            target = torch.zeros(VOCAB, dtype=torch.float64)
            target[stream[t]] = 1.0
            if arm == 'A3-soft-frozenW':
                # dormancy: both specialist WEIGHTS stay at their initial
                # uniform-prior values; only the inverse covariances are
                # advanced on the current feature stream. (An rls_update with
                # zero error would leave W unchanged but would also advance P
                # once; here P is advanced exactly once, by rls_refresh_P.)
                P0 = rls_refresh_P(P0, phi)
                P1 = rls_refresh_P(P1, phi)
            else:
                W0, P0 = rls_update(W0, P0, phi, target, w0)
                W1, P1 = rls_update(W1, P1, phi, target, w1)

    stream_ppl = float(np.exp(np.nanmean(ce[1:])))
    neg_frac = float(nneg) / (T - 1)
    clip_frac = float(nclip) / (T - 1)
    stream_ppl_unclipped = (float(np.exp(np.nanmean(ce_unc[1:])))
                            if n_unc_undef < (T - 1) else float('nan'))
    if arm == 'A3-soft-frozenW':
        assert_W_still_frozen(W0, W0_init, arm, seed)
        assert_W_still_frozen(W1, W1_init, arm, seed)

    # T_adapt (s18 protocol, known switches)
    t_adapts = []
    switch_times = [SEG_LEN * s for s in range(1, N_SEGMENTS)]
    for si, t_s in enumerate(switch_times):
        seg_end = SEG_LEN * (si + 2) if si + 2 <= N_SEGMENTS else T
        seg_ce = ce[t_s:seg_end]
        if seg_ce.size == 0:
            continue
        steady = float(np.exp(np.mean(seg_ce[-STEADY_WINDOW:])))
        thr = steady * T_ADAPT_RATIO
        cum = np.concatenate([[0.0], seg_ce])
        found = None
        for j in range(T_ADAPT_WINDOW, seg_ce.shape[0] + 1):
            wppl = np.exp((cum[j] - cum[j - T_ADAPT_WINDOW])
                          / T_ADAPT_WINDOW)
            if wppl <= thr:
                found = j
                break
        t_adapts.append(float(found) if found is not None else float('nan'))

    # Forgetting: domain-matched specialist (A3) or single readout (A1)
    forgets = []
    forgets_unc = []
    fneg = 0
    fclip = 0
    n_f_undef = 0
    hold_ce_all = []
    hold_ce_unc_all = []
    for si, t_s in enumerate(switch_times):
        prev_dom = int(domains[t_s - 1])
        hold = gen_stream(seed * 41 + si * 211 + 3,
                          1 if prev_dom == 0 else 7, HOLDOUT_LEN,
                          BIAS_A if prev_dom == 0 else BIAS_B)
        hh = torch.zeros(N_STATE, dtype=torch.float64)
        if arm == 'A1':
            Wf = W
        else:
            Wf = W0 if prev_dom == 0 else W1
        ces = []
        ces_unc = []
        for t in range(1, HOLDOUT_LEN):
            hh = A * hh + B[:, hold[t - 1]]
            phi = torch.cat([B[:, hold[t - 1]],
                             torch.ones(1, dtype=torch.float64)])
            y_tok = (Wf @ phi)[hold[t]]
            p_t = float(y_tok.clamp(min=1e-12, max=1.0))
            yt = float(y_tok)
            if yt <= 0.0:
                fneg += 1
            if yt <= 1e-12:
                fclip += 1
            if yt > 0.0:
                ces_unc.append(-np.log(yt))
                hold_ce_unc_all.append(-np.log(yt))
            else:
                n_f_undef += 1
                hold_ce_unc_all.append(np.nan)
            ces.append(-np.log(p_t))
            hold_ce_all.append(-np.log(p_t))
        forgets.append(float(np.exp(np.mean(ces))))
        forgets_unc.append(float(np.exp(np.mean(ces_unc)))
                           if ces_unc else float('nan'))
    forgetting_ppl = float(np.mean(forgets))
    forgetting_ppl_unclipped = (float(np.nanmean(forgets_unc))
                                if forgets_unc else float('nan'))
    n_hold = (HOLDOUT_LEN - 1) * max(1, len(forgets))
    forget_neg_frac = float(fneg) / n_hold if n_hold else float('nan')
    forget_clip_frac = float(fclip) / n_hold if n_hold else float('nan')

    save_stream_and_holdout(
        's21', arm, seed, f'tau{tau_m:g}', ce, ce_unc,
        np.asarray(hold_ce_all, dtype=np.float64),
        np.asarray(hold_ce_unc_all, dtype=np.float64))

    return {'exp': 'E1', 'arm': arm, 'tau_m': float(tau_m), 'seed': seed,
            'stream_ppl': stream_ppl, 'neg_frac': neg_frac,
            't_adapt_mean': float(np.nanmean(t_adapts))
            if t_adapts else float('nan'),
            'forgetting_ppl': forgetting_ppl,
            'clip_frac': clip_frac,
            'stream_ppl_unclipped': stream_ppl_unclipped,
            'stream_n_unc_undefined': int(n_unc_undef),
            'forget_neg_frac': forget_neg_frac,
            'forget_clip_frac': forget_clip_frac,
            'forgetting_ppl_unclipped': forgetting_ppl_unclipped,
            'forget_n_unc_undefined': int(n_f_undef),
            'runtime_s': time.time() - t0}


# ========================== E2: M5 state-norm homeostat ==========================

def refs_full_reg(seed, A, B, scale, regulated):
    """Full-state metadata references, optionally under regulation."""
    refs = []
    for d in range(2):
        rs = gen_stream(seed * 31 + d * 131 + 7, 1 if d == 0 else 7,
                        REF_LEN, BIAS_A if d == 0 else BIAS_B)
        h = torch.zeros(N_STATE, dtype=torch.float64)
        acc = torch.zeros(N_STATE, dtype=torch.float64)
        dt = 1.0
        for t in range(REF_LEN):
            if regulated:
                h = torch.pow(A, dt) * h + B[:, rs[t]]
            else:
                h = A * h + B[:, rs[t]]
            hw = h * scale
            acc = acc + hw
            if regulated:
                n = float(torch.norm(hw))
                dt = min(max(dt + E2_ETA * (n - E2_U), 1.0), E2_DT_MAX)
        refs.append(acc / REF_LEN)
    return refs


def run_e2(args):
    """(reg, dist, seed) -> E2 metrics. Mechanism-level, honest scope."""
    if hasattr(sys.stdout, 'reconfigure'):
        sys.stdout.reconfigure(line_buffering=True)
        sys.stderr.reconfigure(line_buffering=True)
    reg, dist, seed = args
    arm = f"{'REG' if reg else 'BARE'}-{'dist' if dist else 'clean'}"
    t0 = time.time()

    torch.manual_seed(seed * SEED_SCALE + SEED_OFF)
    A, B = sample_substrate(seed, 'CV')
    scale = whiten_scale(A)
    stream, domains = gen_drift_stream(seed)
    T = stream.shape[0]

    refs = refs_full_reg(seed, A, B, scale, reg)
    slow = refs[0].clone()
    prev_est = 0
    flips = 0
    h = torch.zeros(N_STATE, dtype=torch.float64)
    dt = 1.0
    norms = np.empty(T, dtype=np.float64)
    dts = []
    spike_t = SEG_LEN
    recovery = None
    rng = np.random.RandomState(seed * 17 + 5)
    u = torch.from_numpy(rng.randn(N_STATE) / np.sqrt(N_STATE))

    for t in range(1, T):
        if reg:
            h = torch.pow(A, dt) * h + B[:, stream[t - 1]]
        else:
            h = A * h + B[:, stream[t - 1]]
        if dist and t == spike_t:
            h = h + E2_SPIKE * u
        hw = h * scale
        norms[t] = float(torch.norm(hw))
        if reg:
            dt = min(max(dt + E2_ETA * (norms[t] - E2_U), 1.0), E2_DT_MAX)
            dts.append(dt)
        # full-state EMA detector
        lam = 1.0 / TAU_M
        slow = (1.0 - lam) * slow + lam * hw
        est = gate_estimate(slow, refs, prev_est, GATE_MARGIN)
        if est != prev_est:
            flips += 1
            prev_est = est
        # recovery: first t after the spike with norm back in band
        if dist and recovery is None and t > spike_t and \
                norms[t] <= E2_U * E2_BAND:
            recovery = t - spike_t

    norm_mean = float(np.nanmean(norms[1:]))
    norm_max = float(np.nanmax(norms[1:]))
    norm_final = float(norms[-1])
    return {'exp': 'E2', 'arm': arm, 'reg': bool(reg), 'dist': bool(dist),
            'seed': seed, 'flips': int(flips), 'norm_mean': norm_mean,
            'norm_max': norm_max, 'norm_final': norm_final,
            'recovery_tokens': float(recovery) if recovery is not None
            else float('nan'),
            'dt_mean': float(np.mean(dts)) if dts else float('nan'),
            'dt_max': float(np.max(dts)) if dts else float('nan'),
            'runtime_s': time.time() - t0}


# ========================== Aggregation ==========================

def aggregate(results):
    groups = {}
    for r in results:
        groups.setdefault((r['exp'], r['arm']), []).append(r)
    agg = []
    for (exp, arm), rs in sorted(groups.items()):
        entry = {'exp': exp, 'arm': arm, 'n_runs': len(rs)}
        for m in rs[0]:
            if m in ('exp', 'arm', 'seed', 'runtime_s', 'reg', 'dist',
                     'tau_m'):
                continue
            v = np.array([r[m] for r in rs], dtype=float)
            v = v[~np.isnan(v)]
            entry[m + '_mean'] = float(np.mean(v)) if v.size else float('nan')
        if 'flips_mean' in entry:
            entry['flips_mean'] = float(np.mean([r['flips'] for r in rs]))
        agg.append(entry)
    return agg


