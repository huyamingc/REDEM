def load_e1_committed():
    """E1 rows of the committed s21 CSV, for paired comparison in the probe."""
    with open(CSV_PATH) as f:
        return [r for r in csv.DictReader(f) if r['exp'] == 'E1']


def dispatch(task):
    """Top-level Pool worker: (exp, args) -> run_e1 or run_e2."""
    exp, a = task
    return run_e1(a) if exp == 'E1' else run_e2(a)


def run_frozen_p_probe():
    """Isolation probe for dormant-covariance refresh.

    A3-soft (E1) trains both specialist readouts. This probe repeats the same
    integration with the weights frozen and only the inverse covariances
    refreshed, so the soft-routing stream cost can be split into the
    routing-rule change and the covariance refresh instead of being reported
    as one bundled flip. Writes its own file; does not touch the E1/E2
    artifacts.
    """
    t_start = time.time()
    print(f"[{time.strftime('%H:%M:%S')}] START S21 frozen-P probe "
          f"(A3-soft-frozenW, {N_SEEDS} seeds)")
    args = [('A3-soft-frozenW', TAU_M, s) for s in range(N_SEEDS)]
    rows = []
    for i, a in enumerate(args):
        rows.append(run_e1(a))
        print(f"[{time.strftime('%H:%M:%S')}] progress {i + 1}/{len(args)}",
              flush=True)

    def _delta(field, ref_arm):
        base = {r['seed']: r[field] for r in rows}
        ref = {int(r['seed']): float(r[field])
               for r in load_e1_committed() if r['arm'] == ref_arm}
        seeds = sorted(s for s in base if s in ref)
        d = np.array([base[s] - ref[s] for s in seeds])
        return {'vs': ref_arm,
                'diff_mean': float(d.mean()),
                'better_n': int(np.sum(d < 0)), 'n': int(d.size),
                'frozenW': {str(s): float(base[s]) for s in seeds},
                'reference': {str(s): float(ref[s]) for s in seeds}}

    out = {
        'params': {
            'experiment': 'dormant-covariance refresh isolation (P3 claim)',
            'arms': {'A3-soft': 'E1 reference (weights trained, s21 CSV)',
                     'A3-soft-frozenW': 'same softmax routing, weights frozen '
                                        'after the first token, inverse '
                                        'covariances refreshed each token'},
            'tau_m': TAU_M, 'n_seeds': N_SEEDS,
            'protocol': 'E1 verbatim (same task/seed rules as the s21 CSV)',
            'note': 'frozenW - A3-soft isolates the covariance refresh; '
                    'both are measured against the same per-seed A1 baseline',
            'env': {'torch': torch.__version__, 'numpy': np.__version__,
                    'cpu': 'torch CPU only'},
        },
        'stream_vs_a3soft': _delta('stream_ppl', 'A3-soft'),
        'stream_vs_a1': _delta('stream_ppl', 'A1'),
        'forgetting_vs_a3soft': _delta('forgetting_ppl', 'A3-soft'),
        'rows': rows,
    }
    out_path = os.path.join(DATA_DIR, 's37_dormant_p_probe_v1.json')
    with open(out_path, 'w') as f:
        json.dump(out, f, indent=2)
    d = out['stream_vs_a3soft']
    print(f"\nfrozenW - A3-soft stream: {d['diff_mean']:+.3f} "
          f"(frozenW better on {d['better_n']}/{d['n']})")
    print(f"JSON: {out_path}")
    check_paper_fixtures(out)
    print(f"[{time.strftime('%H:%M:%S')}] DONE, total "
          f"{time.time() - t_start:.1f}s")


def check_paper_fixtures(out):
    """Recompute the numbers Paper D quotes from committed data and report any
    drift from the constants at the top of this file (the manuscript's quoted
    values). Reports only; never rewrites the constants."""
    print("\n--- paper-fixture check (quoted values vs committed data) ---")
    problems = 0

    # (1) dormant-covariance isolation vs the probe that was just written
    fw = out['stream_vs_a3soft']['frozenW']
    worst = max(abs(float(v) - S37_CHANCE_PPL) for v in fw.values())
    ok = worst <= 1e-9
    problems += not ok
    print(f"  frozenW-only stream ppl: max|data - {S37_CHANCE_PPL:g}| = "
          f"{worst:.2e} over {len(fw)} seeds -> {'OK' if ok else 'DRIFT'} "
          "(the frozen arm must sit exactly at the uniform prior)")
    for label, key in [('frozenW - A3-soft stream', 'stream_vs_a3soft')]:
        d = out[key]
        if d['better_n'] != 0:
            problems += 1
            print(f"  {label}: expected the frozen arm to lose on all seeds, "
                  f"got better_n={d['better_n']} -> DRIFT")

    # (2) M3 detector counts and the detection-conditioned forgetting gain,
    #     both from the s20 CSV
    s20_path = os.path.join(DATA_DIR, 's20_ssm_m3_routing_v1.csv')
    rows = list(csv.DictReader(open(s20_path)))
    if rows and 'switches_detected' in rows[0]:
        a1 = {int(r['seed']): float(r['forgetting_ppl'])
              for r in rows if r['arm'] == 'A1'}
        for tm, const in S20_DETECTED.items():
            ds = [int(r['switches_detected']) for r in rows
                  if r['arm'] == 'A3' and float(r['tau_m']) == tm]
            got = sum(ds) / len(ds)
            ok = abs(got - const) <= 0.005
            problems += not ok
            print(f"  M3 detections tau_m={tm:g}: data {got:.2f}/5 vs paper "
                  f"{const:.2f} -> {'OK' if ok else 'DRIFT'}")
        det, nod = [], []
        for r in rows:
            if r['arm'] != 'A3':
                continue
            g = float(r['forgetting_ppl']) - a1[int(r['seed'])]
            (det if int(r['switches_detected']) > 0 else nod).append(g)
        for label, grp, const in [
                ('gain when detected >=1', det,
                 -S20_FORGET_GAIN_WHEN_DETECTED),
                ('gain when detected =0 ', nod, -S20_FORGET_GAIN_WHEN_NOT)]:
            got = sum(grp) / len(grp)
            ok = abs(got - const) <= 0.005
            problems += not ok
            print(f"  {label}: data {got:.4f} vs paper {const:.2f} "
                  f"-> {'OK' if ok else 'DRIFT'}")
    else:
        print("  s20 CSV has no switches_detected column -> re-run "
              "s20_ssm_m3_routing.py to enable this check")
    print(f"--- {problems} drift(s) ---")


